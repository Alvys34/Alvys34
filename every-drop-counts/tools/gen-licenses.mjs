#!/usr/bin/env node
/**
 * Generates src/ui/licenses.js (third-party notices shown on the Credits screen) from the ACTUAL
 * installed dependencies: the web game's runtime deps (package.json "dependencies") plus the
 * desktop wrapper's runtime pieces (Electron, steamworks.js) when desktop/node_modules exists.
 *
 *   node tools/gen-licenses.mjs          # rewrite src/ui/licenses.js
 *
 * Re-run after adding/upgrading a dependency. If a desktop module is not installed, the previous
 * entry for it is kept (so the file never loses a notice just because `desktop/` wasn't `npm ci`'d).
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'src/ui/licenses.js');

const PURPOSE = {
  three: 'Rendering',
  '@dimforge/rapier3d-compat': 'Physics',
  '@fontsource-variable/nunito': 'Typeface (Nunito)',
  electron: 'Desktop runtime',
  'steamworks.js': 'Steam integration',
};

function readPkg(dir) {
  const pj = join(dir, 'package.json');
  if (!existsSync(pj)) return null;
  const pkg = JSON.parse(readFileSync(pj, 'utf8'));
  const lic = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
  const text = lic ? readFileSync(join(dir, lic), 'utf8').replace(/\r\n/g, '\n').trim() : '';
  const license = typeof pkg.license === 'string' ? pkg.license : (pkg.license && pkg.license.type) || 'see text';
  return { name: pkg.name, version: pkg.version, license, purpose: PURPOSE[pkg.name] || '', text };
}

const rootPkg = JSON.parse(readFileSync(resolve(ROOT, 'package.json'), 'utf8'));
const entries = [];
for (const name of Object.keys(rootPkg.dependencies || {})) {
  const e = readPkg(resolve(ROOT, 'node_modules', name));
  if (e) entries.push(e); else console.warn(`[licenses] ${name} not installed — skipped`);
}

let previous = [];
if (existsSync(OUT)) {
  try { previous = (await import(pathToFileURL(OUT).href + `?t=${Date.now()}`)).LICENSES || []; } catch { previous = []; }
}
for (const name of ['electron', 'steamworks.js']) {
  const e = readPkg(resolve(ROOT, 'desktop/node_modules', name));
  if (e) entries.push(e);
  else {
    const old = previous.find((p) => p.name === name);
    if (old) entries.push(old); else console.warn(`[licenses] desktop/${name} not installed and no previous entry`);
  }
}

const body = `/**
 * GENERATED by tools/gen-licenses.mjs from the installed dependencies — do not edit by hand.
 * Third-party notices shown on the Credits screen.
 */
export const LICENSES = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(OUT, body);
console.log(`wrote ${OUT}: ${entries.map((e) => `${e.name}@${e.version} (${e.license})`).join(', ')}`);
